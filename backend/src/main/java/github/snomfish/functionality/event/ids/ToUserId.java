package github.snomfish.functionality.event.ids;

import static github.snomfish.functionality.event.ids.ToTargetId.*;
import static github.snomfish.functionality.event.ids.GeneralId.*;

public enum ToUserId implements IToSideId {
    NULL_EVENT(ToTargetId.NULL_EVENT, GeneralId.NULL_EVENT), // should never be dispatched

    SELF_SWAPPED_IN(WATCHES_OPP_SWAP_IN, LOOMIAN_SWAPS_IN),
    SELF_KNOCKED_OUT_OPP(SELF_KNOCKED_OUT_BY_OPP, LOOMIAN_KNOCKED_OUT),

    // move
    SELF_PRE_MOVE(SELF_WATCHES_OPP_PRE_MOVE, LOOMIAN_PRE_MOVE),
    SELF_PRE_ACCURACY_CHECK(SELF_WATCHES_OPP_PRE_ACCURACY_CHECK, PRE_CHECK_ACCURACY),
    SELF_CLUTCHES(SELF_WATCHES_OPP_CLUTCH, LOOMIAN_CLUTCHES),
    SELF_POST_MOVE(SELF_WATCHES_OPP_POST_MOVE, LOOMIAN_POST_MOVE),

    // formula damage
    PRE_SELF_DEAL_FORMULA_DAMAGE(PRE_OPP_DEAL_FORMULA_DAMAGE, PRE_DEAL_FORMULA_DAMAGE),
    SELF_PRE_DAMAGING(SELF_PRE_DAMAGED, LOOMIAN_PRE_DAMAGED),
    SELF_MOVE_HIT(HIT_BY_MOVE, LOOMIAN_MOVE_HIT),
    SELF_MOVE_DEALT_DAMAGE(RECEIVED_DAMAGE_FROM_MOVE, LOOMIAN_DEALT_FORMULA_DAMAGE),
    SELF_PRE_DRAINING_HEALTH(SELF_PRE_HEALTH_DRAINED, LOOMIAN_PRE_HEATH_DRAINED),
    SELF_PRE_DRAINING_ENERGY(SELF_PRE_ENERGY_DRAINED, LOOMIAN_PRE_ENERGY_DRAINED),

    // item
    SELF_CONSUMED_ITEM(SELF_WATCHES_OPP_CONSUME_ITEM, LOOMIAN_CONSUMES_ITEM),
    SELF_LOSES_ITEM(SELF_WATCHES_OPP_LOSE_ITEM, LOOMIAN_LOSES_ITEM),

    // stat changes
    SELF_PRE_STATS_CHANGED(OPP_PRE_STATS_CHANGED, PRE_LOOMIAN_STATS_CHANGED),
    SELF_STATS_LOWERED_BY_OPP(LOWERED_OPP_STATS, LOOMIAN_HAD_STATS_LOWERED),
    SELF_STATS_LOWERED_BY_SELF(WATCHES_OPP_LOWER_OPP_STATS, LOOMIAN_HAD_STATS_LOWERED),

    // weather
    SELF_SET_WEATHER(OPP_SET_WEATHER, LOOMIAN_SET_WEATHER),
    ;


    private ToTargetId oppId;
    private GeneralId isoId;


    private ToUserId(
        ToTargetId oppId,
        GeneralId isoId
    ) {
        this.oppId = oppId;
        this.isoId = isoId;
    }


    public ToTargetId oppId() {return oppId;}
    public GeneralId isoId() {return isoId;}
}
