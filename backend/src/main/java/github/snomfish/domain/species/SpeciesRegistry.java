	private static boolean initialised = false;
    private static final Map<SpeciesId, Species> registry = new HashMap<>();


    private SpeciesRegistry() {}


	public static Species get(SpeciesId id) {
		if (!initialised) throw new IllegalArgumentException("species has not been initialised");
		return registry.get(id);
    } 


    public static void register(
        SpeciesId speciesId,
        String name,
        List<TypeId> baseTypes,
        List<AbilityId> baseAbilities,
        int health,
        int energy,
        int mAttack,
        int mDefense,
        int rAttack,
        int rDefense,
        int speed,
        int bst,
        double weight,
        double height,
        List<MoveId> learnset,
		boolean canEvolve
    ) {
        Species species = new Species(
            speciesId,
            name,
            baseTypes,
            baseAbilities,
            new Stats(
                health,
                energy,
                mAttack,
                mDefense,
                rAttack,
                rDefense,
                speed
            ),
            bst,
            weight,
            height,
            learnset,
			canEvolve
        );
        registry.put(speciesId, species);
    }


